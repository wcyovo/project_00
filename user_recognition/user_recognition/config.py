# -*- coding: utf-8 -*-
"""全局配置：路径与用户识别算法参数

本文件集中管理所有路径与超参数：
- 数据 / 输出路径集中在此配置，换机器只需改这一处；
- 算法相关参数（帧尺寸、嵌入维度、相似度度量、训练测试划分比例等）
  统一定义，避免散落各处造成不一致。
"""

import os


# ---------------------------------------------------------------------------
# 路径配置
# ---------------------------------------------------------------------------

# 项目根目录：本文件（config.py）位于项目根目录下的 user_recognition/ 子目录，
# 用 __file__ 向上两级即可得到项目根目录。
# 使用 __file__ 推导而非写死绝对路径，保证代码拷贝到任何电脑都能正确定位。
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# 数据根目录（存放原始 txt 压力数据）
# 采用"相对路径"：数据已放在项目根目录下的 data/ 文件夹中，
# 即 <项目根目录>/data/睡姿数据。
# 若换机器后数据位置不同，两种改法任选其一：
#   1) 设置环境变量 DATA_ROOT 覆盖（推荐，不改代码）；
#   2) 直接修改下方 os.path.join(...) 中的相对路径。
DATA_ROOT = os.environ.get(
    "DATA_ROOT",
    os.path.join(BASE_DIR, "data", "睡姿数据"),
)

# 输出目录：存放运行产生的全部图表与 JSON 接口文件，
# 固定位于项目根目录下的 output/ 文件夹（首次运行会自动创建）。
OUTPUT_DIR = os.path.join(BASE_DIR, "output")

# 身高体重信息文件：readme.md 记录每个被测者的姓名、身高、体重，
# 与数据目录同级（位于项目根目录 data/ 下），因此取 DATA_ROOT 的父目录。
INFO_FILE = os.path.join(
    os.path.dirname(DATA_ROOT), "readme.md"
)


# ---------------------------------------------------------------------------
# 数据格式参数
# ---------------------------------------------------------------------------

# 每帧压力图的尺寸：44 行 x 24 列，对应智能床垫上的传感器阵列布局。
ROWS = 44
COLS = 24

# 动作编号 -> 睡姿类别的映射。
# 数据集约定：动作 1~6 仰卧，7~9 俯卧，10~15 左侧卧，16~21 右侧卧。
# 这里把 21 个动作归并为 0~3 四类睡姿，供"按睡姿注册多模板"等功能使用。
ACTION_TO_POSE = {}
for _a in range(1, 7):
    ACTION_TO_POSE[_a] = 0          # 仰卧
for _a in range(7, 10):
    ACTION_TO_POSE[_a] = 1          # 俯卧
for _a in range(10, 16):
    ACTION_TO_POSE[_a] = 2          # 左侧卧
for _a in range(16, 22):
    ACTION_TO_POSE[_a] = 3          # 右侧卧


# ---------------------------------------------------------------------------
# 模型参数
# ---------------------------------------------------------------------------

# 特征嵌入维度：网络把 1056 维压力帧（44*24）压缩到 64 维。
# 维度太低会丢失区分信息；太高则计算量大且容易过拟合。
EMBED_DIM = 64


# ---------------------------------------------------------------------------
# 匹配参数
# ---------------------------------------------------------------------------

# 相似度度量方式：余弦相似度（向量夹角余弦，范围 [-1,1]）。
# 它只关注"方向"而非"模长"，适合本任务——
# 嵌入已做 L2 归一化，此时余弦相似度等价于向量的内积，计算快速稳定。
SIMILARITY_METRIC = "cosine"

# 每个用户注册的模板数量：按睡姿聚类成 4 个（对应四类睡姿）。
# 这样无论查询帧是什么睡姿，都能匹配到"该用户最接近的那个睡姿模板"，
# 从而实现睡姿无关的用户识别。
TEMPLATES_PER_USER = 4


# ---------------------------------------------------------------------------
# 数据划分参数
# ---------------------------------------------------------------------------

# 按用户划分训练/测试：70% 用户作为训练（注册）用户，30% 作为"新用户"测试。
# 目的：模拟真实场景——只有部分人的数据用于建库，其余人视为未注册陌生人，
# 用来评估系统的拒识（FAR）能力。
TRAIN_USER_RATIO = 0.7

# 随机种子：固定后每次运行的用户划分、数据增强结果可复现，便于与他人比较。
RANDOM_SEED = 42